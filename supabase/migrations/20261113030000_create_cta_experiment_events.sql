create table if not exists public.cta_experiment_events (
  id bigint generated by default as identity primary key,
  event_id text not null unique,
  experiment_key text not null,
  event_type text not null check (event_type in ('exposure', 'click', 'lead')),
  variant_key text not null check (variant_key in ('a', 'b', 'c', 'd')),
  visitor_id text not null,
  session_id text not null,
  location text,
  page_path text,
  lead_id uuid references public.leads(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists idx_cta_experiment_events_rollup
  on public.cta_experiment_events (experiment_key, created_at desc, variant_key, event_type);

alter table public.cta_experiment_events enable row level security;
revoke all on public.cta_experiment_events from anon, authenticated;
grant all on public.cta_experiment_events to service_role;

create or replace function public.cta_experiment_stats(
  p_days integer default 7,
  p_experiment_key text default 'partneragency_cta_copy_v1'
)
returns table (
  period text,
  variant_key text,
  exposures bigint,
  clicks bigint,
  leads bigint
)
language sql
stable
security invoker
set search_path = public
as $$
  with periods(period, started_at, ended_at) as (
    values
      ('current'::text, now() - make_interval(days => greatest(1, least(p_days, 90))), now()),
      ('previous'::text, now() - make_interval(days => greatest(1, least(p_days, 90)) * 2), now() - make_interval(days => greatest(1, least(p_days, 90))))
  ), variants(variant_key) as (
    values ('a'::text), ('b'::text), ('c'::text), ('d'::text)
  )
  select
    p.period,
    v.variant_key,
    count(e.id) filter (where e.event_type = 'exposure')::bigint as exposures,
    count(e.id) filter (where e.event_type = 'click')::bigint as clicks,
    count(e.id) filter (where e.event_type = 'lead')::bigint as leads
  from periods p
  cross join variants v
  left join public.cta_experiment_events e
    on e.experiment_key = p_experiment_key
   and e.variant_key = v.variant_key
   and e.created_at >= p.started_at
   and e.created_at < p.ended_at
  group by p.period, v.variant_key
  order by p.period, v.variant_key;
$$;

revoke all on function public.cta_experiment_stats(integer, text) from public, anon, authenticated;
grant execute on function public.cta_experiment_stats(integer, text) to service_role;
